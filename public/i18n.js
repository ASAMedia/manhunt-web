function detect() {
  try {
    const saved = localStorage.getItem('mh_lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* kein Speicher */ }
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export const lang = detect();
document.documentElement.lang = lang;

export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// Statische Texte im HTML: data-i18n="schlüssel", data-i18n-placeholder, data-i18n-title
export function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
}

export function switchLang() {
  try { localStorage.setItem('mh_lang', lang === 'de' ? 'en' : 'de'); } catch { /* nur für diese Seite */ }
  location.reload();
}

// Sprachknopf (z. B. oben rechts) – lädt die Seite in der anderen Sprache neu
export function langButton(cls = 'btn sm') {
  const b = document.createElement('button');
  b.type = 'button';
  b.className = `${cls} lang-toggle`;
  b.textContent = t('lang.switch');
  b.title = t('lang.switchTitle');
  b.addEventListener('click', switchLang);
  return b;
}

// Kopfzeilen für Spieler-Anfragen: Fehlermeldungen des Servers kommen dann in der passenden Sprache
export const langHeader = { 'X-Lang': lang };
